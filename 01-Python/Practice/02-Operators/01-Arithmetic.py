# return the sum of two numbers
def add(a,b):
    return a + b

# return the difference of two numbers
def subtract(a,b):
    return a - b

# return the product of two numbers
def multiply(a,b):
    return a * b

# return the quotient of two numbers with floating point division
def divide(a,b):
    return a / b
# return the remainder of the division of two numbers
def modulus(a,b):
    return a % b

# return the quotient of two numbers without decimal part
def floor_division(a,b):
    return a // b

# return the result of a number raised to the power of another number
def exponentiation(a,b):
    return a ** b

print(add(3,4))
print(subtract(10,5))
print(multiply(6,7))
print(divide(10,3))
print(modulus(10,3))
print(floor_division(10,3))
print(exponentiation(2,3))