-- Create the reporting table
CREATE or replace TABLE  ANALYTICS_DB.HR.EMPLOYEE_REPORT  as 
SELECT E.EMPLOYEE_ID,
    E.EMPLOYEE_NAME,
    D.DEPARTMENT_NAME,
    D.LOCATION,
    E.SALARY,
    E.JOIN_DATE from  RAW_DB.HR.EMPLOYEE E left join  RAW_DB.HR.DEPARTMENT D
on E.EMPLOYEE_ID = D.DEPARTMENT_ID ;

-- Validate reporting table
SELECT *
FROM ANALYTICS_DB.HR.EMPLOYEE_REPORT
ORDER BY EMPLOYEE_ID;

